package artifactmeta

import (
	"strings"
	"testing"
)

const validSource = `// Code generated by scripts/go-module-origin/generator; DO NOT EDIT.

package artifact

import _ "embed"

// Payload is the zstd-compressed liblancedb.so for linux/amd64.
//
//go:embed "liblancedb.so.zst"
var Payload []byte

const (
	Target              = "linux/amd64"
	LibraryName         = "liblancedb.so"
	CompressedSize    int64 = 11
	CompressedSHA256    = "1111111111111111111111111111111111111111111111111111111111111111"
	UncompressedSize  int64 = 22
	UncompressedSHA256  = "2222222222222222222222222222222222222222222222222222222222222222"
	UpstreamRepo        = "lancedb/lancedb-c"
	UpstreamCommit      = "3106de158b8da5dcb47e2a4acc820ed1b74b3e01"
	HeaderSHA256        = "3333333333333333333333333333333333333333333333333333333333333333"
)
`

func TestParseSourceAcceptsGeneratedModule(t *testing.T) {
	meta, err := ParseSource([]byte(validSource))
	if err != nil {
		t.Fatalf("ParseSource: %v", err)
	}
	if meta.Target != "linux/amd64" || meta.LibraryName != "liblancedb.so" || meta.PayloadName != "liblancedb.so.zst" {
		t.Fatalf("unexpected metadata: %+v", meta)
	}
	if meta.CompressedSize != 11 || meta.UncompressedSize != 22 {
		t.Fatalf("unexpected sizes: %+v", meta)
	}
	if meta.UpstreamCommit != "3106de158b8da5dcb47e2a4acc820ed1b74b3e01" {
		t.Fatalf("unexpected commit: %q", meta.UpstreamCommit)
	}
}

func TestParseSourceRejectsMutations(t *testing.T) {
	cases := []struct {
		name   string
		source string
		want   string
	}{
		{"renamed payload", strings.Replace(validSource, "var Payload", "var Other", 1), "exactly one variable"},
		{"initialized payload", strings.Replace(validSource, "var Payload []byte", "var Payload = []byte{}", 1), "must not have an initializer"},
		{"wrong payload type", strings.Replace(validSource, "var Payload []byte", "var Payload string", 1), "type []byte"},
		{"missing embed", strings.Replace(validSource, "//go:embed", "//embed", 1), "exactly one go:embed"},
		{"two embeds", strings.Replace(validSource, "//go:embed \"liblancedb.so.zst\"", "//go:embed \"liblancedb.so.zst\"\n//go:embed \"liblancedb.so.zst\"", 1), "exactly one go:embed"},
		{"missing constant", strings.Replace(validSource, "\tUpstreamRepo        = \"lancedb/lancedb-c\"\n", "", 1), "missing constant UpstreamRepo"},
		{"bad commit", strings.Replace(validSource, "3106de158b8da5dcb47e2a4acc820ed1b74b3e01", "not-a-commit", 1), "40-character lowercase hex"},
		{"foreign import", strings.Replace(validSource, "import _ \"embed\"", "import (\n\t_ \"embed\"\n\t_ \"os\"\n)", 1), "must import only embed"},
		{"extra function", validSource + "\nfunc init() {}\n", "only imports and constant or variable declarations"},
		{"foreign package", strings.Replace(validSource, "package artifact", "package other", 1), "want artifact"},
		{"zero size", strings.Replace(validSource, "CompressedSize    int64 = 11", "CompressedSize    int64 = 0", 1), "not positive"},
	}
	for _, testCase := range cases {
		t.Run(testCase.name, func(t *testing.T) {
			_, err := ParseSource([]byte(testCase.source))
			if err == nil {
				t.Fatal("ParseSource accepted a mutated module")
			}
			if !strings.Contains(err.Error(), testCase.want) {
				t.Fatalf("error %q does not contain %q", err, testCase.want)
			}
		})
	}
}
